// Helper functions
export function getLessonById(idOrSlug: string): Lesson | undefined {
  return LESSONS.find((l) => l.id === idOrSlug || l.slug === idOrSlug);
}

export function getPreviousLesson(current: Lesson): Lesson | null {
  const idx = LESSONS.findIndex((l) => l.id === current.id);
  if (idx > 0) return LESSONS[idx - 1];
  return null;
}

export function getNextLesson(current: Lesson): Lesson | null {
  const idx = LESSONS.findIndex((l) => l.id === current.id);
  if (idx !== -1 && idx < LESSONS.length - 1) return LESSONS[idx + 1];
  return null;
}
